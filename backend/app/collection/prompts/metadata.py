"""Prompt templates for trip description generation.

The trip title (trip_name) is no longer generated by an agent — it is set
instantly by Python as soon as the destination is known, using a simple
template like "Trip to {destination}". No LLM call needed for the title.

This agent only runs post-confirmation and generates a trip_description
(one sentence). Scope is determined earlier by internet-backed geography research.
"""

from __future__ import annotations

# Removes trip_name generation from the metadata agent — the title is now set by Python immediately when the destination is known.
METADATA_SYSTEM_PROMPT = """
Generate a concise trip description from the confirmed trip details.
Do not generate a trip name or title — that is handled separately.
Return all fields in the structured output using this exact shape:
{
  "trip_name": null,
  "trip_description": "<one sentence trip description>",
  "trip_scope": null
}
Keep trip_name and trip_scope as null. The application owns those values.
No markdown. No preamble. Raw JSON only.
""".strip()


def build_metadata_task_prompt(memory_json: str) -> str:
    """Build the metadata generation task from confirmed trip memory."""

    return f"Trip memory JSON:\n{memory_json}"
